"""Stage 2: turns the markers in stage1.docx into boxes with Word content controls,
adds the photo placeholder images, and writes the add-in's insert snippets (addin/ooxml.js)."""
import html, json, os, re, subprocess, zipfile
import boxes as B

here = os.path.dirname(os.path.abspath(__file__))
addin = os.path.join(here, "..", "addin")
labels = json.loads(subprocess.check_output(
    ["node", "-e", "console.log(JSON.stringify(require('../addin/data.js').labels))"], cwd=here))

z = zipfile.ZipFile(os.path.join(here, "stage1.docx"))
files = {n: z.read(n) for n in z.namelist()}
doc = files["word/document.xml"].decode("utf8")
ids = B.Ids()


def render(m):
    o = json.loads(html.unescape(m.group(1)))
    t = o["t"]
    if t == "kv":
        return B.kv(o["rows"])
    if t == "box":
        return B.box(o["label"])
    if t == "element":
        return B.element(ids, o["title"], o["rec"], o["photos"], labels)
    if t == "cover":
        return B.cover_box()
    if t == "summary":
        return ('<w:sdt><w:sdtPr><w:alias w:val="Summary of condition labels"/><w:tag w:val="rss-summary"/>'
                f'<w:id w:val="{ids()}"/></w:sdtPr><w:sdtContent><w:p/></w:sdtContent></w:sdt>')
    raise ValueError(t)


marker = r'<w:p>(?:<w:pPr>(?:(?!</w:p>).)*?</w:pPr>)?<w:r>(?:<w:rPr>(?:(?!</w:r>).)*?</w:rPr>)?<w:t[^>]*>§§(.*?)§§</w:t></w:r></w:p>'
doc, n = re.subn(marker, render, doc, flags=re.S)
assert "§§" not in doc, "unreplaced marker"
print("markers replaced:", n)
files["word/document.xml"] = doc.encode("utf8")

# styles: Placeholder Text, and bullets linked to List Bullet
numbering = files["word/numbering.xml"].decode("utf8")
bullet_abs = re.search(r'<w:abstractNum [^>]*w:abstractNumId="(\d+)"(?:(?!</w:abstractNum>).)*?w:lvlText w:val="•"', numbering, re.S).group(1)
bullet_num = re.search(rf'<w:num w:numId="(\d+)"><w:abstractNumId w:val="{bullet_abs}"/>', numbering).group(1)
styles = files["word/styles.xml"].decode("utf8")
styles = re.sub(r'(<w:style w:type="paragraph" w:styleId="ListBullet">.*?<w:pPr>)',
                rf'\1<w:numPr><w:numId w:val="{bullet_num}"/></w:numPr>', styles, count=1, flags=re.S)
files["word/styles.xml"] = styles.encode("utf8")

out = os.path.join(here, "RSS_Level3_Template.docx")
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zo:
    for name in z.namelist():
        zo.writestr(name, files[name])
print("written", out)

# ---------- add-in snippets ----------
tk = B.Ids(token=True)
h = lambda style: f'<w:p><w:pPr><w:pStyle w:val="{style}"/></w:pPr><w:r><w:t xml:space="preserve">__TITLE__</w:t></w:r></w:p>'
snips = {}
for rec in (True, False):
    for photos in (True, False):
        key = f"element_{'rec' if rec else 'norec'}_{'photos' if photos else 'nophotos'}"
        snips[key] = h("Heading2") + B.element(tk, "__TITLE__", rec, photos, labels)
snips["advice"] = h("Heading2") + B.box("General advice")
snips["heading1"] = h("Heading1")
js = ("/* Generated by template/post.py. Word content for the boxes the sidebar inserts. Do not edit by hand. */\n"
      "RSS.rows = " + json.dumps(B.ROWS) + ";\n"
      "RSS.snippets = " + json.dumps(snips) + ";\n")
open(os.path.join(addin, "ooxml.js"), "w").write(js)
print("addin/ooxml.js written", len(js), "bytes")
